/**
 * Shared action-icon set (TKT-018).
 *
 * Hand-rolled, stroke-based icons in the same style as the inline SVGs the
 * app already used (lucide-like: 24px viewBox, currentColor, strokeWidth 2).
 * Kept dependency-free on purpose — the project has no icon library and
 * these paths are the ones already in use around the codebase.
 *
 * Usage: <IconEye size={16} className="..." /> — inherits text color.
 */
import type { SVGProps } from "react";

type IconProps = SVGProps<SVGSVGElement> & { size?: number };

function base({ size = 16, ...props }: IconProps) {
  return {
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: "currentColor",
    strokeWidth: 2,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    "aria-hidden": true,
    ...props,
  };
}

